@app.post("/api/provenance/register", summary="Register report commitment on-chain")
def register_provenance(req: RegisterProvenanceRequest) -> Dict[str, Any]:
    if not req.report or not req.report.get("location_id"):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Invalid report payload. 'location_id' is required."
        )

    try:
        record = blockchain_client.register_report(
            report=req.report,
            metadata_uri=req.metadata_uri or "ipfs://climatechain-bd-manifest"
        )
        return {
            "status": "SUCCESS",
            "message": "Report provenance commitment registered successfully.",
            "record": record
        }
    except ValueError as ve:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(ve))
    except ConnectionError as ce:
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail=f"Blockchain RPC unavailable: {str(ce)}")
    except Exception as e:
        logger.error(f"Error during blockchain registration: {e}")
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"Registration failed: {str(e)}")


@app.get("/api/provenance/{report_id}", summary="Lookup registered on-chain commitment by report ID")
def get_provenance_record(report_id: str) -> Dict[str, Any]:
    try:
        record = blockchain_client.get_registered_record(report_id)
        if not record:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Report commitment {report_id} not found."
            )
        return record
    except ConnectionError as ce:
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail=str(ce))


@app.post("/api/provenance/verify", summary="Verify report integrity against blockchain commitment")
def verify_provenance(req: VerifyProvenanceRequest) -> Dict[str, Any]:
    if not req.report:
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail="Report payload is required.")

    result = blockchain_client.verify_report(req.report, report_id=req.report_id)
    return result
