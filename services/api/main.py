@app.get("/api/observations", summary="Retrieve climate observations for a location")
def get_observations(
    location_id: str = Query(..., description="Location identifier (e.g. sylhet-sadar)"),
    start_date: Optional[str] = Query(None, description="Start date YYYY-MM-DD"),
    end_date: Optional[str] = Query(None, description="End date YYYY-MM-DD"),
    limit: int = Query(30, ge=1, le=365)
) -> Dict[str, Any]:
    try:
        loc = get_location_by_id(location_id)
    except KeyError as e:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(e))

    _validate_date_string(start_date, "start_date")
    _validate_date_string(end_date, "end_date")
    if start_date and end_date and start_date > end_date:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="start_date must be on or before end_date.",
        )

    # Live recent window by default; committed samples are the offline fallback.
    records = []
    try:
        if start_date and end_date:
            records = fetch_open_meteo_observations(location_id, start_date, end_date)
        else:
            end_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
            start_str = (
                datetime.now(timezone.utc) - timedelta(days=max(limit, 30) + 7)
            ).strftime("%Y-%m-%d")
            records = fetch_open_meteo_observations(location_id, start_str, end_str)
    except Exception as e:
        logger.warning(f"Error fetching live observations: {e}. Falling back to cache.")
        records = load_cached_samples(location_id)

    if not records:
        records = load_cached_samples(location_id)

    return {
        "location": loc,
        "count": len(records[-limit:]),
        "observations": records[-limit:]
    }


