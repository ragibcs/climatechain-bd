REQUIRED_REPORT_FIELDS = ("location_id", "as_of", "target", "model_version", "risk_level")


def _validate_report_payload(report: Optional[Dict[str, Any]]) -> None:
    if not report:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Report payload is required.",
        )
    missing = [field for field in REQUIRED_REPORT_FIELDS if report.get(field) in (None, "")]
    if missing:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Report is missing required field(s): {', '.join(missing)}.",
        )
    if report.get("data_mode") == "FORECAST":
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Forecast outlooks are model output and cannot be registered as historical provenance.",
        )


@app.post("/api/provenance/register", summary="Register a report commitment")
def register_provenance(req: RegisterProvenanceRequest) -> Dict[str, Any]:
    _validate_report_payload(req.report)

    try:
        record = blockchain_client.register_report(
            report=req.report,
            metadata_uri=req.metadata_uri or "urn:climatechain:report-manifest"
        )
        onchain = record.get("mode") == "ONCHAIN"
        return {
            "status": "SUCCESS",
            "mode": record.get("mode"),
            "message": (
                "Report provenance commitment registered on-chain."
                if onchain
                else "Report commitment stored in the labelled local simulator."
            ),
            "record": record
        }
    except ValueError as ve:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(ve))
    except ConnectionError as ce:
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail=f"Blockchain RPC unavailable: {str(ce)}")
    except Exception as e:
        logger.error(f"Error during blockchain registration: {e}")
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"Registration failed: {str(e)}")


