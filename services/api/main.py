    try:
        return blockchain_client.verify_report(req.report, report_id=req.report_id)
    except Exception as e:
        logger.error(f"Provenance verification error: {e}")
        return {
            "status": ProvenanceVerificationState.UNAVAILABLE,
            "reason": f"Verification dependency error: {str(e)}",
            "computed_hash": None,
            "onchain_hash": None,
            "verified": False,
            "mode": blockchain_client.mode,
        }
