# Overview responses are relatively expensive (four climate queries). Cache them
# for a short window so refreshes and multiple judge sessions stay responsive.
_OVERVIEW_CACHE: Dict[str, Tuple[float, Dict[str, Any]]] = {}
OVERVIEW_TTL_SECONDS = int(os.getenv("OVERVIEW_CACHE_TTL", "300"))


def _cached_overview(key: str) -> Optional[Dict[str, Any]]:
    entry = _OVERVIEW_CACHE.get(key)
    if not entry:
        return None
    created_at, payload = entry
    if time.time() - created_at > OVERVIEW_TTL_SECONDS:
        _OVERVIEW_CACHE.pop(key, None)
        return None
    return payload


def _validate_date_string(value: Optional[str], field_name: str = "as_of") -> None:
    if value is None:
        return
    try:
        datetime.strptime(value, "%Y-%m-%d")
    except ValueError:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"{field_name} must be a valid YYYY-MM-DD date.",
        )


