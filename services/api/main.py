@app.get("/api/health", summary="Service health and external dependency check")
def get_health() -> Dict[str, Any]:
    """
    Distinguishes application operational health from external dependency status
    (Open-Meteo API and Blockchain RPC).
    """
    now = datetime.now(timezone.utc).isoformat()

    # Check blockchain connection. A reachable RPC is not the same as a
    # signer-ready registry, so expose both facts separately.
    try:
        rpc_connected = bool(
            blockchain_client.w3 and blockchain_client.w3.is_connected()
        )
    except Exception:
        rpc_connected = False

    provenance_mode = blockchain_client.mode
    mode_labels = {
        "ONCHAIN": "Sepolia signer ready",
        "ONCHAIN_READ_ONLY": "Sepolia read-only; registration uses the simulator",
        "SIMULATED_FALLBACK": "RPC configured but unavailable; labelled simulator",
        "LOCAL_SIMULATOR": "Local simulator / graceful fallback",
    }
    upstream = get_upstream_status()

    return {
        "status": "healthy",
        "service": "ClimateChain BD API",
        "version": "1.1.0",
        "timestamp": now,
        "uptime_seconds": round(time.time() - START_TIME, 1),
        "environment": {
            "model_version": MODEL_VERSION,
            "target": MODEL_TARGET,
            "chain_id": blockchain_client.chain_id,
            "contract_configured": bool(blockchain_client.contract_address),
            "provenance_mode": provenance_mode,
            "provenance_write_enabled": blockchain_client.can_write_onchain,
            "stations_supported": len(SYLHET_LOCATIONS),
        },
        "features": {
            "station_overview": True,
            "forecast_outlook": True,
            "dataset_manifests": True,
            "verification_states": [
                ProvenanceVerificationState.VERIFIED,
                ProvenanceVerificationState.MISMATCH,
                ProvenanceVerificationState.NOT_FOUND,
                ProvenanceVerificationState.UNAVAILABLE,
                ProvenanceVerificationState.PENDING,
            ],
        },
        "dependencies": {
            "blockchain_rpc_connected": rpc_connected,
            "blockchain_ready": provenance_mode == "ONCHAIN",
            "blockchain_mode": mode_labels.get(provenance_mode, provenance_mode),
            "open_meteo_api": upstream["open_meteo"],
            "open_meteo_last_checked": upstream["last_checked_at"],
            "open_meteo_last_error": upstream["last_error"],
        }
    }


