# --- Pydantic Request / Response Models ---

class PredictionRequest(BaseModel):
    location_id: str = Field(..., description="Sylhet station identifier", json_schema_extra={"example": "sylhet-sadar"})
    as_of: Optional[str] = Field(None, description="Evaluation date (YYYY-MM-DD)", json_schema_extra={"example": "2024-06-20"})
    use_live_api: bool = Field(True, description="Query Open-Meteo live API or use local verified sample")


class RegisterProvenanceRequest(BaseModel):
    report: Dict[str, Any] = Field(..., description="Full report payload generated by /api/predictions")
    metadata_uri: Optional[str] = Field("ipfs://climatechain-bd-manifest", description="Metadata or manifest URI")


class VerifyProvenanceRequest(BaseModel):
    report: Dict[str, Any] = Field(..., description="Report payload to verify")
    report_id: Optional[str] = Field(None, description="Explicit report ID if overridden")


